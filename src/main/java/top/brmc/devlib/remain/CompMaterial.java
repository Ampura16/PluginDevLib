	@Getter
	private final Material material;

	CompMaterial(final int data, final int version, final String... legacy) {
		this.data = (byte) data;
		this.version = version;
		this.legacy = legacy;

		Material mat = null;

		if (!Data.ISFLAT && this.isDuplicated() || (mat = Material.getMaterial(this.name())) == null)
			for (int i = legacy.length - 1; i >= 0; i--) {
				mat = Material.getMaterial(legacy[i]);

				if (mat != null)
					break;
			}

		this.material = CommonCore.getOrDefault(mat, Material.STONE);
	}

	CompMaterial(final int data, final String... legacy) {
		this(data, 0, legacy);
	}

	CompMaterial(final int version) {
		this(0, version);
	}

	CompMaterial() {
		this(0, 0);
	}

	CompMaterial(final String... legacy) {
		this(0, 0, legacy);
	}

