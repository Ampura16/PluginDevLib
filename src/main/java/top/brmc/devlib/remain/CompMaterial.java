	/**
	 * 若给定材质可损坏则返回 true。
	 *
	 * @param type
	 * @return
	 */
	public static boolean isDamageable(final CompMaterial type) {
		ValidCore.checkNotNull(type);

		try {
			if (MinecraftVersion.atLeast(V.v1_13))
				return type.toItem().getItemMeta() instanceof org.bukkit.inventory.meta.Damageable;
		} catch (final Throwable t) {
			// MC unsupported
		}

		switch (type.toString()) {
			case "HELMET":
			case "CHESTPLATE":
			case "LEGGINGS":
			case "BOOTS":
			case "SWORD":
			case "AXE":
			case "PICKAXE":
			case "SHOVEL":
			case "HOE":
			case "ELYTRA":
			case "TURTLE_HELMET":
			case "TRIDENT":
			case "HORSE_ARMOR":
			case "SHEARS":
				return true;
			default:
				return false;
		}
	}

